"""Plain-English explanation of one violation (C3 endpoint 6). ADVISORY ONLY.

Core has already decided that this is a violation, and its message holds the exact facts
(e.g. "49h after ... (limit 48h)"). Gemini only retells those facts in plain English for a
non-technical ops manager: no new numbers, no guessed causes. The explanation never
changes the verdict, and the result always carries `advisory=True` so the UI labels it.

One Gemini call per violation; the disk cache in `client.py` makes repeats free.
"""

from __future__ import annotations

from pydantic import BaseModel, Field

from haqwa.core.report import Violation
from haqwa.core.rules_v2 import RuleV2

from .client import GeminiClient
from .render_v2 import render_rule


# Wire model (no docstring: Pydantic would send it to Gemini as a schema description).
class WireExplanation(BaseModel):
    text: str = Field(
        description="2-3 short sentences: what happened to this entity, using only the given facts"
    )


class Explanation(BaseModel):
    """What the web returns for `/api/v1/explain` (C3)."""

    text: str
    advisory: bool = True  # always True: the verdict comes from core, never from this text
    cached: bool = False


def explain_violation(rule: RuleV2, violation: Violation, *, client: GeminiClient) -> Explanation:
    """Ask Gemini to explain one violation that core already found.

    Raises:
        GeminiError: quota, availability or bad output (see `client.py`). The verdict
            stays valid; the UI just shows no explanation.
    """
    result = client.generate(build_prompt(rule, violation), WireExplanation)
    return Explanation(text=result.value.text.strip(), cached=result.cached)


def build_prompt(rule: RuleV2, violation: Violation) -> str:
    """The explain prompt: rule, its enforced meaning, and the entity's timeline.

    The meaning comes from `render_rule` (code, not Gemini) and already states the owner's
    decisions (resets and ignored events), so Gemini explains what core actually checked.
    """
    lines = []
    for i, e in enumerate(violation.timeline):
        mark = ">>" if i == violation.offending_index else "  "
        data = ", ".join(f"{k}={v}" for k, v in e.data.items() if k != rule.per)
        lines.append(f"{mark} {e.ts.isoformat()}  {e.event}" + (f"  ({data})" if data else ""))
    timeline = "\n".join(lines)
    return f"""You explain a policy violation to a non-technical operations manager.

A deterministic checker has ALREADY decided this is a violation. Do not question,
repeat or change that verdict, and do not judge other rules.

Policy as the owner wrote it: "{rule.source}" (per {rule.per})
What the checker enforces, including the owner's decisions (generated by code):
{render_rule(rule)}

Checker message (exact facts, already verified): {violation.message}

Events for {rule.per} {violation.entity} (oldest first; ">>" marks the event that broke
the policy):
{timeline}

In 2-3 short sentences of plain English, say what happened to {rule.per}
{violation.entity} and how it went against the policy.
- Use only facts from the checker message and the events above.
- Keep times, counts and limits exactly as the checker gives them; do not calculate new ones.
  You may write them naturally: "49h" as "49 hours", dates like "29 Sep, 09:00 UTC".
- Mention the details from the events that matter to the manager (who, what kind, the
  outcome), not just the rule.
- Do not guess why it happened: no causes, reasons, intentions or blame. The events do not
  show them.
No code, no event names in snake_case, no markdown."""
